"""Generate original synthetic fixtures using pymcdm 1.3.1, not copied data.
Run in a private virtual environment, then moon fmt && moon test.
"""
import importlib.metadata
import json
import math
import random
from pathlib import Path
import numpy as np
from pymcdm.methods import TOPSIS, VIKOR, PROMETHEE_II

assert importlib.metadata.version("pymcdm") == "1.3.1"
rng = random.Random(71319)
blocks = ["// Synthetic data generated by scripts/generate_reference.py; not production code."]
for case in range(24):
    n = 5 + case % 3
    matrix = np.array([[rng.randint(1, 100) + j * 0.125 for j in range(3)] for _ in range(n)], dtype=float)
    weights = np.array([rng.randint(1, 9) for _ in range(3)], dtype=float)
    weights /= weights.sum()
    types = np.array([1, -1, 1]) if case % 2 == 0 else np.array([-1, 1, -1])
    top = TOPSIS()(matrix, weights, types)
    vik = VIKOR(v=0.5)(matrix, weights, types)
    pro = PROMETHEE_II("usual")(matrix, weights, types)
    wp = []
    for row in matrix:
        terms = []
        for j in range(3):
            ref = max(matrix[:, j]) if types[j] == 1 else min(matrix[:, j])
            terms.append(weights[j] * types[j] * (math.log(row[j]) - math.log(ref)))
        wp.append(math.fsum(terms))
    def arr(x):
        return json.dumps(np.asarray(x).tolist(), separators=(",", ":"), allow_nan=False)
    dirs = ", ".join("Benefit" if t == 1 else "Cost" for t in types)
    labels = json.dumps([f"a{i}" for i in range(n)])
    blocks.append(f'''///|
test "pymcdm 1.3.1 synthetic differential case {case:02d}" {{
  let m = decision_matrix({labels}, ["x", "y", "z"], [{dirs}], {arr(matrix)})
  let w = {arr(weights)}
  close_arrays(topsis(m, w).ranking.scores, {arr(top)})
  close_arrays(vikor(m, w).ranking.scores, {arr(vik)})
  close_arrays(promethee(m, w, [Usual, Usual, Usual]).ranking.scores, {arr(pro)})
  close_arrays(weighted_product(m, w).ranking.scores, {arr(wp)})
}}
''')
out = Path(__file__).resolve().parents[1] / "reference_wbtest.mbt"
out.write_text("\n".join(blocks), encoding="utf-8")
print("wrote 24 synthetic cases / 96 model score vectors; pymcdm", importlib.metadata.version("pymcdm"))
